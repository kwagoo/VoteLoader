import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const pageNames = ['index.html', 'styles.css', 'app.js'];

export function readPublicPages(directory = path.join(root, 'public')) {
  const pages = {};
  for (const name of pageNames) {
    pages[name] = fs.readFileSync(path.join(directory, name), 'utf8');
  }
  return pages;
}

export function renderEmbeddedModule(pages) {
  return `// Generated by scripts/embed-pages.js. Do not edit.\nexport const embeddedMarker = 'VOTELOADER_EMBEDDED_PAGES';\nexport const pages = ${JSON.stringify(pages)};\n`;
}

const output = path.join(root, 'src', 'embedded-pages.js');
fs.writeFileSync(output, renderEmbeddedModule(readPublicPages()));
